/**
 * Capture authentic public-action acquisition saves from the pre-expansion engine.
 * Run from the repository: node scripts/capture-pre-content-relic-saves.mjs
 * The archived engine is never edited; no deck, HP, reward or RNG state is injected.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceCommit = execFileSync('git', ['rev-parse', '22e43e8'], { cwd: repository, encoding: 'utf8' }).trim();
const archiveDirectory = mkdtempSync(join(tmpdir(), 'spyier-pre-content-relics-'));
const archive = execFileSync('git', ['archive', sourceCommit], { cwd: repository, maxBuffer: 128 * 1024 * 1024 });
execFileSync('tar', ['-x', '-C', archiveDirectory], { input: archive });
symlinkSync(join(repository, 'node_modules'), join(archiveDirectory, 'node_modules'), 'dir');

const server = await createServer({
  root: archiveDirectory, configFile: false, appType: 'custom',
  server: { middlewareMode: true }, logLevel: 'error',
});

try {
  const { createBlessedRun, reduceRun } = await server.ssrLoadModule('/src/engine/run.ts');
  const { serializeRun, deserializeRun } = await server.ssrLoadModule('/src/engine/runPersistence.ts');
  const { RELIC_DEFINITIONS } = await server.ssrLoadModule('/src/data/relics.ts');
  const targets = new Set([
    'ref_lead_paperweight', 'ref_claw', 'ref_arcane_scroll', 'ref_glass_eye',
    'ref_pandora_box', 'ref_jewel_box',
  ]);
  const fixtures = [];
  const facts = [];

  function apply(state, action) {
    const next = reduceRun(state, action);
    if (next === state) throw new Error(`Historical action rejected: ${action.type} @ ${state.screen}`);
    const raw = serializeRun(next);
    if (!deserializeRun(raw)) throw new Error(`Historical engine rejected its own ${action.type} save`);
    return next;
  }

  function capture(state, actions) {
    const raw = serializeRun(state);
    if (serializeRun(deserializeRun(raw)) !== raw) throw new Error('Historical save did not round-trip exactly');
    const acquisition = state.relicAcquisition;
    fixtures.push({
      name: `${acquisition.relicId}-${acquisition.stage}`,
      relicId: acquisition.relicId,
      sourceRelicId: RELIC_DEFINITIONS[acquisition.relicId].sourceRelicId,
      stage: acquisition.stage,
      kind: acquisition.kind ?? null,
      seed: state.seed,
      classId: state.classId,
      actions: structuredClone(actions),
      actionsSha256: createHash('sha256').update(JSON.stringify(actions)).digest('hex'),
      save: JSON.parse(raw),
    });
  }

  for (let index = 0; index < 2500 && targets.size; index++) {
    const initial = createBlessedRun(`relic-acquisition-legal-${index}`, 'machinist');
    for (const option of initial.blessing.options) {
      const reward = option.rewards.find((entry) => entry.kind === 'relic' && targets.has(entry.relicId));
      if (!reward) continue;
      const actions = [
        { type: 'chooseBlessing', optionId: option.id },
        { type: 'confirmBlessing' },
        { type: 'continueBlessing' },
      ];
      let state = initial;
      for (const action of actions) state = apply(state, action);
      if (state.screen !== 'relicAcquisition' || state.relicAcquisition.relicId !== reward.relicId)
        throw new Error(`Historical blessing did not reach ${reward.relicId} acquisition`);
      if (state.relicAcquisition.stage === 'select') {
        capture(state, actions);
        const acquisition = state.relicAcquisition;
        const selectedCount = acquisition.kind === 'transform' ? Math.max(acquisition.minCount, Math.min(2, acquisition.count)) : acquisition.count;
        const select = acquisition.kind === 'chooseCard'
          ? { type: 'selectRelicCards', cardIds: acquisition.offeredCardIds.slice(0, selectedCount) }
          : { type: 'selectRelicCards', cardUids: acquisition.eligibleCardUids.slice(0, selectedCount) };
        const confirm = { type: 'confirmRelicAcquisition' };
        state = apply(state, select); actions.push(select);
        state = apply(state, confirm); actions.push(confirm);
      }
      if (state.relicAcquisition.stage !== 'result') throw new Error('Historical acquisition failed to resolve');
      capture(state, actions);
      facts.push({ relicId: reward.relicId, seed: initial.seed, actionCount: actions.length });
      targets.delete(reward.relicId);
    }
  }
  if (targets.size) throw new Error(`Historical bounded seed search missed: ${[...targets].join(', ')}`);
  const result = {
    sourceCommit,
    provenance: 'Generated by the unmodified git-archived pre-expansion engine using public createBlessedRun/reduceRun actions only. No deck, HP, map, reward, outcome or RNG state injections.',
    generator: { script: 'scripts/capture-pre-content-relic-saves.mjs', seedPrefix: 'relic-acquisition-legal-', classId: 'machinist', seedSearchBound: 2500, facts },
    fixtures,
  };
  const destination = process.argv[2] ? resolve(process.argv[2]) : join(repository, 'src/tests/fixtures/pre-content-expansion-relic-saves.json');
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, `${JSON.stringify(result, null, 2)}\n`);
  console.log(JSON.stringify({ sourceCommit, fixtureCount: fixtures.length, facts, destination }));
} finally {
  await server.close();
}

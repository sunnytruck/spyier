import type { CardDefinition, Effect } from '../types/game';
import { createReferenceCard } from './referenceCard';

type MartialClass = 'berserker' | 'assassin' | 'colorless';
type Version = [description: string, effects: Effect[]];

function define(
  id: string, classId: MartialClass, sourceName: string, name: string,
  type: CardDefinition['type'], glyph: string, normal: Version, upgraded: Version,
  options: Partial<CardDefinition> = {}, rarity: CardDefinition['rarity'] = 'common',
): CardDefinition {
  return createReferenceCard({
    id, classId, sourceName, name, type, glyph,
    description: normal[0], effects: normal[1],
    upgradedDescription: upgraded[0], upgradedEffects: upgraded[1], options, rarity,
  });
}

const damage = (amount: number, extra: Partial<Extract<Effect, { type: 'damage' }>> = {}): Effect => ({ type: 'damage', amount, ...extra });
const block = (amount: number): Effect => ({ type: 'block', amount });
const status = (kind: 'weak' | 'vulnerable' | 'poison', amount: number, all = false): Effect => ({ type: 'status', target: all ? 'allEnemies' : 'enemy', status: kind, amount });
const energy = (amount: number): Effect => ({ type: 'energy', amount });


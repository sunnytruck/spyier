/**
 * Executable definitions transcribed from the supplied CP932 relic list.
 * Every source number and complete effect is preserved. No unfinished relic is registered.
 * Source-name aliases of existing IWASON relics are attached to the original IDs in relics.ts.
 */
function referenceRelic(
  id: string, name: string, sourceRelicId: string, glyph: string, rarity: RelicRarity,
  description: string, effects: RelicEffect[],
  options: { classId?: ClassId; passive?: RelicPassives } = {},
): RelicDefinition {
  const acquisition = rarity === 'shop' || rarity === 'event' ? rarity : 'normal';
  const hooks = effects.length ? effects : [{ trigger: 'acquire', kind: 'run', amount: 0 } satisfies RelicEffect];
  return { id, name, sourceRelicName: name, sourceRelicId, glyph, rarity, acquisition,
    description, effect: hooks[0], ...(hooks.length > 1 ? { effects: hooks } : {}), ...options };
}

